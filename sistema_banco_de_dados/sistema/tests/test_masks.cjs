const assert = require('node:assert/strict');
const m = require('../static/forms.js');
assert.equal(m.formatCPF('01234567890'), '012.345.678-90');
assert.equal(m.formatCPF('012.345.678-90'), '012.345.678-90');
assert.equal(m.formatCPF('(012) 345 / 678 - 90'), '012.345.678-90');
assert.equal(m.formatCPF('0123456789012345'), '012.345.678-90');
assert.equal(m.formatCPF('11111111111'), '111.111.111-11');
assert.equal(m.formatCPF(''), '');
assert.equal(m.formatCPF('0123'), '012.3');
assert.equal(m.formatPhone('11900000000'), '(11) 90000-0000');
assert.equal(m.formatPhone('1130000000'), '(11) 3000-0000');
assert.equal(m.formatPhone('119000000009999'), '(11) 90000-0000');
assert.equal(m.format('+55 (11) 90000-0000', 'phone', true), '(11) 90000-0000');
assert.equal(m.format('+55 11 3000-0000', 'phone', true), '(11) 3000-0000');
assert.equal(m.format('55123456789', 'phone', true), '(55) 12345-6789');
assert.equal(m.format('', 'phone', false), '');
assert.equal(m.positionForDigits('012.345.678-90', 4), 5);
assert.equal(m.positionForDigits('(11) 90000-0000', 3), 6);
assert.equal(m.formatFileSize(450), '450 bytes');
assert.equal(m.formatFileSize(1024), '1 KB');
assert.equal(m.formatFileSize(1048576), '1 MB');
console.log('OK: máscaras, zeros iniciais, limite de dígitos, telefone fixo/celular, +55 e posição do cursor.');
